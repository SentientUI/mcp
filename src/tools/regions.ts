import { z } from 'zod/v3';
import type { ApiClient } from '../api-client.js';
import { rangeQuery, type RangeArgs } from './common.js';

// Regions: <Adaptive> components served through the slot path — children-only
// (generated versions), hybrids (children + hand-written `variants`), and
// Edit-on-site regions. /components never lists them (it reads the variants
// path), so list_components and get_variant_performance were blind to them:
// measured 2026-11-02, sentient-ui.com's live hero (hero_cta_v4, a hybrid with
// exposures on all three arms) did not exist as far as any agent could tell,
// and an agent asked about "the hero button" reported the retired v3's numbers.
// The numbers come from /slots, the same payload the dashboard's Components
// list renders for these rows.

type SlotArmPersona = {
  persona: string;
  personaDisplay?: string;
  timesShown?: number;
  evidence_state?: unknown;
  evidence_stats?: { probBeatsControl?: unknown } | null;
};

type SlotArm = { arm: string; timesShown?: number; conversions?: number; personas?: SlotArmPersona[] };

export type SlotsResponse = {
  slots?: Array<{ slotId: string; baselineArm?: string | null; arms?: SlotArm[] }>;
  window_totals?: Array<{ slotId: string; visitors?: number; conversions?: number; unconfirmedConversions?: number }>;
};

/** Where a version came from: the page's original, a `variants` key written
 *  in code, generated by AI, or written by a person in the dashboard or the
 *  on-site editor. The API classifies it (arm-sources.ts, on
 *  /slot-definitions); without that answer it is read off the arm id. */
export type VersionSource = 'original' | 'code' | 'generated' | 'written';

export type RegionVersion = {
  versionId: string;
  source: VersionSource;
  timesShown: number;
  conversions: number;
  conversionRate: number | null;
  evidence: Array<{ audience: string; state: string | null; probBeatsBaseline: number | null; timesShown: number }>;
};

export type Region = {
  componentId: string;
  /** People in the requested window who were served this region (null when the API sent no window totals). */
  windowVisitors: number | null;
  windowConversions: number | null;
  versions: RegionVersion[];
};

export const regionOutputSchema = z
  .array(
    z.object({
      componentId: z.string(),
      windowVisitors: z.number().nullable().describe('People served this region in the requested window; null on an older API'),
      windowConversions: z.number().nullable().describe('Of those, People who converted; null on an older API'),
      versions: z.array(
        z.object({
          versionId: z.string().describe('The served arm id: baseline = the original, authored.<key> = a version written in code, anything else = generated or edited in the dashboard'),
          source: z.enum(['original', 'code', 'generated', 'written']).describe('written = by a person in the dashboard or the on-site editor'),
          timesShown: z.number().describe("All-time times shown — the optimizer's own totals, NOT filtered by the requested window"),
          conversions: z.number().describe('All-time conversions credited to this version (optimizer totals)'),
          conversionRate: z.number().nullable().describe('conversions / timesShown; null at 0 shown'),
          evidence: z
            .array(
              z.object({
                audience: z.string().describe('The audience the evidence is scoped to (Everyone when no audiences are in use)'),
                state: z.string().nullable().describe('not_enough_data | early_signal | moderate_evidence | strong_evidence | likely_worse | inconclusive'),
                probBeatsBaseline: z.number().nullable(),
                timesShown: z.number(),
              }),
            )
            .describe("The server's per-audience evidence for this version against the region's baseline"),
        }),
      ),
    }),
  )
  .describe('Regions: components served per visitor through Who sees what — versions written in code next to the original, or generated ones');

/** The API's per-arm source (slot-definitions' classifyArms), by slot then arm. */
export type ArmSources = Map<string, Map<string, string>>;

function sourceOf(arm: string, baselineArm: string, known?: string): VersionSource {
  // Every non-original arm used to read "generated": Astra Trade's two
  // versions, typed by hand in the on-site editor, were reported to agents as
  // AI-written (2026-11-19).
  if (known === 'original' || known === 'generated') return known;
  if (known === 'authored') return 'code';
  if (known === 'manual') return 'written';
  if (known === 'suggested') return 'generated';
  if (arm === baselineArm) return 'original';
  if (arm.startsWith('authored.')) return 'code';
  return 'generated';
}

export function regionsFrom(body: SlotsResponse | null | undefined, sources?: ArmSources): Region[] {
  const totals = new Map((body?.window_totals ?? []).map((t) => [t.slotId, t]));
  return (body?.slots ?? []).map((s) => {
    const baselineArm = s.baselineArm ?? 'baseline';
    const t = totals.get(s.slotId);
    const versions = (s.arms ?? []).map((a): RegionVersion => {
      const shown = a.timesShown ?? 0;
      const conv = a.conversions ?? 0;
      return {
        versionId: a.arm,
        source: sourceOf(a.arm, baselineArm, sources?.get(s.slotId)?.get(a.arm)),
        timesShown: shown,
        conversions: conv,
        conversionRate: shown > 0 ? conv / shown : null,
        evidence: (a.personas ?? []).map((p) => ({
          audience: p.personaDisplay ?? p.persona,
          state: typeof p.evidence_state === 'string' ? p.evidence_state : null,
          probBeatsBaseline: typeof p.evidence_stats?.probBeatsControl === 'number' ? p.evidence_stats.probBeatsControl : null,
          timesShown: p.timesShown ?? 0,
        })),
      };
    });
    // Original first, then code, then generated — the order the dashboard reads.
    const rank: Record<VersionSource, number> = { original: 0, code: 1, written: 2, generated: 3 };
    versions.sort((x, y) => rank[x.source] - rank[y.source] || x.versionId.localeCompare(y.versionId));
    return {
      componentId: s.slotId,
      windowVisitors: typeof t?.visitors === 'number' ? t.visitors : null,
      windowConversions: typeof t?.conversions === 'number' ? t.conversions : null,
      versions,
    };
  });
}

export async function fetchRegions(client: Pick<ApiClient, 'get'>, projectId: string, rangeArgs: RangeArgs): Promise<Region[]> {
  const id = encodeURIComponent(projectId);
  const [body, defs] = await Promise.all([
    client.get<SlotsResponse>(`/projects/${id}/slots${rangeQuery(rangeArgs)}`),
    // Sources are a label: without them the arm-id rule still answers.
    client.get<{ slots?: Array<{ slot_id?: string; arms?: Array<{ id?: string; source?: string }> }> }>(`/projects/${id}/slot-definitions`).catch(() => null),
  ]);
  const sources: ArmSources = new Map();
  for (const d of defs?.slots ?? []) {
    if (typeof d.slot_id !== 'string') continue;
    sources.set(d.slot_id, new Map((d.arms ?? []).filter((a) => typeof a.id === 'string' && typeof a.source === 'string').map((a) => [a.id!, a.source!])));
  }
  return regionsFrom(body, sources);
}

const SOURCE_LABEL: Record<VersionSource, string> = { original: 'original', code: 'written in code', generated: 'generated', written: 'written by a person' };

/** One text block per region. Ids are visitor-mintable — callers pass `untrusted`. */
export function regionText(r: Region, untrusted: (s: string) => string): string {
  const head =
    `${untrusted(r.componentId)} — region, ${r.versions.length} version${r.versions.length === 1 ? '' : 's'}` +
    (r.windowVisitors !== null ? ` · ${r.windowVisitors} People served in this window, ${r.windowConversions ?? 0} converted` : '');
  const lines = r.versions.map((v) => {
    const rate = v.conversionRate === null ? 'not shown yet' : `${v.conversions}/${v.timesShown} (${(v.conversionRate * 100).toFixed(1)}%)`;
    const ev = v.source === 'original' ? '' : v.evidence.map((e) => ` · ${untrusted(e.audience)}: ${e.state ?? 'no evidence'}`).join('');
    return `  - ${untrusted(v.versionId)} (${SOURCE_LABEL[v.source]}): ${rate} all time${ev}`;
  });
  return [head, ...lines].join('\n');
}
